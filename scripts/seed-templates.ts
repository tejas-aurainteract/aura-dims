async function seedTemplates() {
  console.log('Seeding Aura DIMS starter template pack (8 starter layouts)...');
  const now = new Date().toISOString();
  let created = 0;
  let updated = 0;

  for (const t of STARTER_TEMPLATES) {
    const docRef = db.collection('templates').doc(t.id);
    const snap = await docRef.get();

    const record: TemplateRecord = {
      id: t.id,
      title: t.title,
      description: t.description,
      category: t.category,
      scope: 'global',
      departmentId: null,
      orientation: t.orientation,
      dimensions: t.document.dimensions,
      schemaVersion: '1.0.0',
      status: 'active',
      document: t.document,
      thumbnailSvg: null,
      createdBy: 'system-bootstrap',
      createdAt: snap.exists ? (snap.data() as TemplateRecord).createdAt : now,
      updatedAt: now,
    };

    if (snap.exists) {
      await docRef.set(record, { merge: true });
      updated++;
      console.log(`  [UPDATE] ${t.title} (${t.orientation}) -> ${t.id}`);
    } else {
      await docRef.set(record);
      created++;
      console.log(`  [CREATE] ${t.title} (${t.orientation}) -> ${t.id}`);
    }
  }

  console.log(`\nStarter template pack successfully seeded: ${created} created, ${updated} updated.`);
}

seedTemplates()
  .then(() => process.exit(0))
  .catch((err) => {
    console.error('Template seeding failed:', err);
    process.exit(1);
  });
